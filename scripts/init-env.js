// Creates server/.env with random secrets the first time you run `npm run setup`.
import { existsSync, writeFileSync } from 'node:fs';
import { randomBytes } from 'node:crypto';

const path = new URL('../server/.env', import.meta.url);
if (existsSync(path)) {
  console.log('server/.env already exists — keeping it.');
} else {
  const pw = () => randomBytes(9).toString('base64url');
  writeFileSync(path, `# Generated by scripts/init-env.js
DATABASE_URL="postgresql://postgres:postgres@localhost:5433/gva"
DATABASE_URL_UNPOOLED="postgresql://postgres:postgres@localhost:5433/gva"
API_PORT=4000
JWT_SECRET="${randomBytes(32).toString('hex')}"

# Login codes are emailed when SMTP is set. If SMTP_HOST is empty (development),
# the code is printed in the server console and shown on the sign-in screen.
SMTP_HOST=""
SMTP_PORT=587
SMTP_USER=""
SMTP_PASS=""
MAIL_FROM="GVA Sales Pipeline <no-reply@gva.local>"

# Seed accounts (used by npm run seed)
SEED_ADMIN_PASSWORD="${pw()}"
SEED_DEMO_PASSWORD="${pw()}"
`);
  console.log('Created server/.env (seed passwords are inside it).');
}
